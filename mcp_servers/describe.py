"""Writes docs/TOOLS.md and the schema snapshot from the live servers, so the docs
can never drift from the code.   Run:  python -m mcp_servers.describe"""
from __future__ import annotations

import asyncio
import json
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "tests" / "contract" / "tool_schemas.json"
AUTH = "Bearer token on the HTTP endpoint (one token per user)"
THIRD_PARTY = """
## Third-party servers (not written by us)

| Server | Used for | Auth | Why we trust it |
|---|---|---|---|
| Upwork official MCP (`https://mcp.upwork.com/mcp`) | Live mode: job search, proposal drafts, messages | OAuth 2.1, tokens stored encrypted per user | Run by the marketplace itself, and every write is a draft the user confirms on Upwork. |
| GitHub MCP server | Reading the user's repositories for portfolio ingestion | GitHub token with read-only repo scope | Official GitHub server; we give it a read-only token and only call its read tools. |
"""


async def collect() -> dict:
    from mcp_servers.marketplace.server import build_server as market
    from mcp_servers.portfolio.server import build_server as portfolio
    from mcp_servers.workspace.server import build_server as workspace
    tmp = tempfile.mkdtemp()
    servers = {"marketplace": market(lambda user: None, audit_path=f"{tmp}/m.jsonl"),
               "portfolio": portfolio(audit_path=f"{tmp}/p.jsonl"),
               "workspace": workspace(store_path=f"{tmp}/w.json", audit_path=f"{tmp}/w.jsonl")}
    out = {}
    for name, server in servers.items():
        for t in await server.list_tools():
            out[f"{name}.{t.name}"] = {"description": t.description, "input": t.inputSchema, "output": t.outputSchema,
                                       "annotations": t.annotations.model_dump(exclude_none=True)}
    return out


def tools_md(tools: dict) -> str:
    rows = ["# Tools", "", "Generated by `python -m mcp_servers.describe`. One row per MCP tool.", "",
            "| Tool | Server | Read or write | Annotations | Auth | What it does |", "|---|---|---|---|---|---|"]
    for key, t in tools.items():
        server, name = key.split(".")
        a = t["annotations"]
        notes = ", ".join(k for k in ("readOnlyHint", "destructiveHint", "idempotentHint", "openWorldHint") if a.get(k))
        rows.append(f"| `{name}` | {server} | {'read' if a.get('readOnlyHint') else 'write'} | {notes} | {AUTH} | "
                    f"{t['description'].splitlines()[0]} |")
    rows += ["", "Every write tool takes an `idempotency_key`; marketplace writes also take `dry_run`.",
             "Every call is written to an append-only audit log (user, tool, arguments, result, trace id) with PII masked.",
             THIRD_PARTY]
    return "\n".join(rows)


if __name__ == "__main__":
    tools = asyncio.run(collect())
    SNAPSHOT.write_text(json.dumps(tools, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    (ROOT / "docs" / "TOOLS.md").write_text(tools_md(tools), encoding="utf-8")
    print(f"{len(tools)} tools written to docs/TOOLS.md and {SNAPSHOT.relative_to(ROOT)}")
